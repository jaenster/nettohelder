import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { caos2026 } from '../src/cao-2026.js';
import { caoCatalog2026 } from '../src/cao-catalog.js';
import type { CaoIndexEntry } from '../src/cao-index.js';

/**
 * Lift the light per-CAO fields out of caos2026 and the catalogue, and check that
 * each record is the one export of caos/<id>.ts, so it can be imported on its own.
 * Ordered like the catalogue (sector by sector), CAOs outside it last.
 */
export async function readCaoIndex(caosDir: string): Promise<CaoIndexEntry[]> {
  const listed = caoCatalog2026.flatMap((s) =>
    s.caos.filter((c) => c.calculable && c.caoId).map((c) => ({ id: c.caoId!, name: c.name, sector: s.sector })),
  );
  const byId = new Map(caos2026.map((cao) => [cao.id, cao]));
  const order = [...listed.map((l) => l.id), ...caos2026.map((c) => c.id).filter((id) => !listed.some((l) => l.id === id))];

  const out: CaoIndexEntry[] = [];
  for (const id of order) {
    const cao = byId.get(id);
    if (!cao) throw new Error(`catalogue lists ${id}, but caos2026 has no such record`);
    const file = join(caosDir, `${id}.ts`);
    if (!existsSync(file)) throw new Error(`${id}: expected its record in caos/${id}.ts`);
    const mod = (await import(pathToFileURL(file).href)) as Record<string, unknown>;
    const exports = Object.values(mod);
    if (exports.length !== 1 || exports[0] !== cao)
      throw new Error(`${id}: caos/${id}.ts must export exactly the record in caos2026, and nothing else`);
    const l = listed.find((x) => x.id === id);
    out.push({ id, name: l?.name ?? cao.name, ...(l ? { sector: l.sector } : {}), kind: cao.salary.kind });
  }
  return out;
}

export function renderCaoIndex(entries: CaoIndexEntry[]): string {
  return [
    '// Generated by scripts/gen-cao-index.ts from caos2026 and the catalogue. Do not edit.',
    "import type { Cao } from './types.js';",
    "import type { CaoIndexEntry } from './cao-index.js';",
    '',
    'export const caoIndex2026: CaoIndexEntry[] = [',
    ...entries.map((e) => `  ${JSON.stringify(e)},`),
    '];',
    '',
    '/** One dynamic import per CAO, so a page only downloads the record it shows. Each module exports just that record. */',
    'export const caoLoaders2026: Record<string, () => Promise<Record<string, Cao>>> = {',
    ...entries.map((e) => `  ${JSON.stringify(e.id)}: () => import('./caos/${e.id}.js'),`),
    '};',
    '',
  ].join('\n');
}
