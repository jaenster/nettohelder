import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { CaoMetaEntry } from '../src/core/types.js';

const DRAFT_RE = /DRAFT from cao-pipeline \(confidence: (high|medium|low)\)/;
const ID_RE = /^\s{2}id: '([^']+)'/m;

/**
 * The draft marker lives only in each CAO file's header comment, so it is lifted
 * out of the source once and shipped as data alongside the bundle.
 */
export function readCaoMeta(caosDir: string): Record<string, CaoMetaEntry> {
  const out: Record<string, CaoMetaEntry> = {};
  for (const file of readdirSync(caosDir).filter((f) => f.endsWith('.ts')).sort()) {
    const src = readFileSync(join(caosDir, file), 'utf8');
    const id = ID_RE.exec(src)?.[1];
    if (!id) continue;
    const m = DRAFT_RE.exec(src);
    out[id] = m ? { draft: true, confidence: m[1] as NonNullable<CaoMetaEntry['confidence']> } : { draft: false };
  }
  return out;
}

export function renderCaoMeta(meta: Record<string, CaoMetaEntry>): string {
  const lines = Object.entries(meta).map(([id, m]) => `  ${JSON.stringify(id)}: ${JSON.stringify(m)},`);
  return [
    '// Generated by scripts/gen-cao-meta.ts from the headers in packages/figures/src/caos. Do not edit.',
    "import type { CaoMetaEntry } from './types.js';",
    '',
    'export const caoMeta: Record<string, CaoMetaEntry> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}
